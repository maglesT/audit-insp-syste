"""FDA work list (D47): one row per FDA must/should document, in the owner's build order, with its status.

  python3 tools/fda/worklist.py          # writes docs/fda-worklist.md from sources/catalog.csv + library/fda-status.json

Status per document (library/fda-status.json, edited as the build goes): not started / drafted / verified /
in review / done, plus items, automatic-route passes, review-queue size and agent usage (tokens).
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STATUS = ROOT / "library" / "fda-status.json"
OUT = ROOT / "docs" / "fda-worklist.md"

# The owner's order (D47). Within a group, documents not named come after the named ones, must before should.
ORDER = [
    ("1 XML", ["ecfr-21cfr211-2026-10-27.xml", "ecfr-21cfr210-2026-10-27.xml", "fda-cfr-21-part-11.xml",
               "fda-cfr-21-314.81.xml", "fda-cfr-21-314.70.xml", "fda-cfr-21-part-200.xml", "fda-cfr-21-part-207.xml",
               "fda-cfr-21-part-4.xml"]),
    ("2 HTML", ["fda-cgmp-qa-", "fda-ora-guide-", "fda-itg-", "fda-cpg-490-200-parametric-release.html",
                "fda-alert-benzene-contamination.html"]),
    ("3 Guidance PDF", ["fda-aseptic-2004.pdf", "fda-guidance-quality-systems-approach-2006.pdf",
                        "fda-guidance-part11-scope-application-2003.pdf", "fda-guidance-quality-agreements-2016.pdf",
                        "fda-guidance-nitrosamine-control-2024.pdf", "fda-guidance-npbl-cross-contamination-2013.pdf",
                        "fda-guidance-cci-in-lieu-of-sterility-2008.pdf", "fda-guidance-pyrogen-endotoxins-qa-2026.pdf",
                        "fda-guidance-field-alert-report-qa-2021.pdf"]),
    ("4 Compliance program", ["fda-cp-7356-002-drug-manufacturing-inspections.pdf", "fda-cp-7356-002a-sterile-drug-process.pdf",
                              "fda-cp-7346-832-preapproval-inspections.pdf", "fda-cp-7356-843-postapproval-inspections.pdf",
                              "fda-cp-7356-021-dqrs-field-alerts.pdf"]),
]
# Deferred (D47, D17): scoped only to LIQ/SEMI or only to API.
DEFERRED = {"fda-guidance-deg-eg-high-risk-components-2023.pdf", "fda-guidance-methanol-testing-alcohol-2023.pdf",
            "fda-guidance-benzene-carbomers-2023.pdf", "fda-ora-guide-topical-drug-products-1994.html",
            "fda-ora-guide-oral-solutions-suspensions-1994.html", "fda-cp-7356-002f-api.pdf"}
PROFILE = {"1 XML": "eCFR XML: text read directly, exact-text quote check, clause number from the structure",
           "2 HTML": "FDA HTML: text read directly, exact-text quote check, Q&A or paragraph number",
           "3 Guidance PDF": "text first, vision only on table/figure pages, two-reader quote check",
           "4 Compliance program": "vision on table pages with the column-header rule, two-reader quote check"}


def group_of(f):
    if f.endswith(".xml"):
        return "1 XML"
    if f.endswith(".html"):
        return "2 HTML"
    return "4 Compliance program" if f.startswith("fda-cp-") else "3 Guidance PDF"


def rank(row):
    g = group_of(row["file"])
    names = dict(ORDER)[g]
    pos = next((i for i, n in enumerate(names) if row["file"] == n or (n.endswith("-") and row["file"].startswith(n))),
               len(names))
    return (g, row["file"] in DEFERRED, pos, row["priority"] != "must", row["file"])


def main():
    rows = [r for r in csv.DictReader(open(ROOT / "sources" / "catalog.csv", encoding="utf-8"))
            if r["regulator"] == "FDA" and r["priority"] in ("must", "should")]
    status = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    out = ["# FDA work list (D47)", "", "Generated by `python3 tools/fda/worklist.py` from `sources/catalog.csv` and "
           "`library/fda-status.json`. Order: the owner's (D47); deferred documents last in their group (D17). "
           "An item ships only when proven (automatic route or review queue, D47).", ""]
    for g, _ in ORDER:
        group = sorted((r for r in rows if group_of(r["file"]) == g), key=rank)
        out += [f"## Group {g}", "", f"Profile: {PROFILE[g]}.", "",
                "| # | Document | Priority | Plants | Status | Items | Auto-route | Review queue | Usage (k tokens) |",
                "|---|---|---|---|---|---|---|---|---|"]
        for n, r in enumerate(group, start=1):
            st = status.get(r["file"], {})
            state = "deferred (D17)" if r["file"] in DEFERRED else st.get("status", "not started")
            out.append(f"| {n} | {r['file']} | {r['priority']} | {r['applies_to']} | {state} | {st.get('items', '')} "
                       f"| {st.get('auto', '')} | {st.get('queue', '')} | {st.get('usage_k', '')} |")
        out.append("")
    out.append(f"{len(rows)} documents ({len(DEFERRED)} deferred).")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
